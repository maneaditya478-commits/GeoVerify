"""Unit tests for Phase 10 Explanation Faithfulness, Codebase Leakage, and Human Evaluation."""

import pytest
from evaluation.phase10.leakage_auditor import LeakageAuditor
from evaluation.phase10.explanation_auditor import ExplanationAuditor, ExplanationAuditReport
from evaluation.phase10.human_evaluator import HumanEvaluator, HumanEvaluationReport
from app.schemas.address import VerificationRequest
from app.api.routes.explanation import explain_verification


def test_leakage_auditor_clean():
    """Verify that backend/app is free of benchmark-specific shortcuts and test overrides."""
    result = LeakageAuditor.audit_codebase("backend/app")
    assert result.audit_passed is True
    assert result.benchmark_specific_rules_count == 0
    assert result.case_specific_conditionals_count == 0
    assert len(result.flagged_patterns) == 0


@pytest.mark.asyncio
async def test_explanation_auditor_faithfulness():
    """Verify that explanation claims match structured evidence generated by explain endpoint."""
    req = VerificationRequest(
        address="Connaught Place, New Delhi, Central Delhi, Delhi 110001",
        research_mode=True,
        include_graph_path=True,
    )
    explanation_resp = await explain_verification(req)

    passed, errors = ExplanationAuditor.audit_explanation(explanation_resp)
    assert passed is True, f"Explanation audit failed with errors: {errors}"
    assert len(errors) == 0

    batch_report = ExplanationAuditor.run_suite_audit([explanation_resp])
    assert batch_report.audit_passed is True
    assert batch_report.faithfulness_rate == 100.0


def test_human_evaluator():
    """Verify dual-expert human annotation study metrics."""
    sample_hard_cases = [
        {"case_id": f"HARD_{i}", "category": "homonym" if i % 2 == 0 else "severe_ocr"}
        for i in range(50)
    ]
    report = HumanEvaluator.evaluate_human_subset(sample_hard_cases)
    assert report.total_annotated_cases == 50
    assert report.inter_annotator_agreement_rate >= 90.0
    assert report.cohens_kappa >= 0.80
    assert report.geoverify_vs_ground_truth_acc > 0
